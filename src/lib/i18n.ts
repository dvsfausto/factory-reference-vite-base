const DICT: Record<Lang, Record<string, string>> = { en: EN, es: ES }

/** Translate a furniture key for the site's language. Unknown key/lang → English → the key itself. */
export function tr(key: keyof typeof EN): string {
  return DICT[SITE_LANGUAGE]?.[key] ?? EN[key] ?? (key as string)
}

